use ring::rand::{SecureRandom, SystemRandom};
use scrypt::{Params, scrypt};
use unicode_normalization::UnicodeNormalization;

fn hex(bytes: &[u8]) -> String {
    const DIGITS: &[u8; 16] = b"0123456789abcdef";
    let mut result = String::with_capacity(bytes.len() * 2);
    for byte in bytes {
        result.push(DIGITS[(byte >> 4) as usize] as char);
        result.push(DIGITS[(byte & 15) as usize] as char);
    }
    result
}

fn derive(password: &str, salt: &str) -> Result<[u8; 64], &'static str> {
    let normalized: String = password.nfkc().collect();
    let params = Params::new(14, 16, 1, 64).map_err(|_| "invalid scrypt parameters")?;
    let mut key = [0; 64];
    scrypt(normalized.as_bytes(), salt.as_bytes(), &params, &mut key)
        .map_err(|_| "scrypt failed")?;
    Ok(key)
}

pub fn hash_password(password: &str) -> Result<String, &'static str> {
    let mut salt = [0; 16];
    SystemRandom::new()
        .fill(&mut salt)
        .map_err(|_| "random salt generation failed")?;
    let salt = hex(&salt);
    Ok(format!("{}:{}", salt, hex(&derive(password, &salt)?)))
}

pub fn verify_password(password: &str, stored: &str) -> bool {
    let mut parts = stored.split(':');
    let (Some(salt), Some(expected)) = (parts.next(), parts.next()) else {
        return false;
    };
    if salt.is_empty() || expected.len() != 128 {
        return false;
    }
    let Ok(key) = derive(password, salt) else {
        return false;
    };
    #[allow(deprecated)]
    ring::constant_time::verify_slices_are_equal(hex(&key).as_bytes(), expected.as_bytes()).is_ok()
}

#[cfg(test)]
mod tests {
    use super::{hash_password, verify_password};

    #[test]
    fn better_auth_bun_interoperability() {
        // Generated by the installed Better Auth package in Bun using synthetic data.
        let fixture = "195481588d82f3a3f1c05d7546f5fddf:2b0f4f9a0f46e3a7ec5cf693db034684e395b98a0eac74c88d0c6aaa6e9f4b168677cd6c09aff9e2cc6863c3ac68d3f08c9a3b80e9da2ee4219deabdd21cc0a6";
        assert!(verify_password("Cafe\u{301}-\u{212b}", fixture));
        assert!(verify_password("Café-Å", fixture));
        assert!(!verify_password("wrong", fixture));
        assert!(!verify_password("wrong", "invalid"));
        let first = hash_password("synthetic password").unwrap();
        let second = hash_password("synthetic password").unwrap();
        assert_ne!(first, second);
        assert!(verify_password("synthetic password", &first));
    }
}
