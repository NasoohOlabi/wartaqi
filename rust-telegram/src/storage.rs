use std::{
    error::Error,
    path::Path,
    time::{SystemTime, UNIX_EPOCH},
};

use base64::{Engine, engine::general_purpose::STANDARD};
use ring::{
    aead,
    rand::{SecureRandom, SystemRandom},
};
use rusqlite::{Connection, OptionalExtension, params};
use serde_json::Value;

type Result<T> = std::result::Result<T, Box<dyn Error + Send + Sync>>;

/// Reads and writes the existing Bun worker's encrypted SQLite state.
pub struct Storage {
    db: Connection,
    key: aead::LessSafeKey,
}

impl Storage {
    pub fn open(path: impl AsRef<Path>, key: &str) -> Result<Self> {
        let bytes = STANDARD.decode(key)?;
        let key = aead::UnboundKey::new(&aead::AES_256_GCM, &bytes)
            .map_err(|_| "TELEGRAM_STORAGE_KEY must be a base64-encoded 32-byte key")?;
        let db = Connection::open(path)?;
        db.execute_batch("PRAGMA journal_mode = WAL; CREATE TABLE IF NOT EXISTS state (key TEXT PRIMARY KEY, value TEXT NOT NULL, expires INTEGER NOT NULL)")?;
        Ok(Self {
            db,
            key: aead::LessSafeKey::new(key),
        })
    }

    pub fn set(&self, name: &str, value: &Value, expires: i64) -> Result<()> {
        let mut nonce = [0; 12];
        SystemRandom::new()
            .fill(&mut nonce)
            .map_err(|_| "random nonce generation failed")?;
        let mut ciphertext = serde_json::to_vec(value)?;
        let tag = self
            .key
            .seal_in_place_separate_tag(
                aead::Nonce::assume_unique_for_key(nonce),
                aead::Aad::from(name.as_bytes()),
                &mut ciphertext,
            )
            .map_err(|_| "state encryption failed")?;
        let mut encoded = Vec::with_capacity(28 + ciphertext.len());
        encoded.extend_from_slice(&nonce);
        encoded.extend_from_slice(tag.as_ref());
        encoded.extend_from_slice(&ciphertext);
        self.db.execute(
            "INSERT OR REPLACE INTO state VALUES (?, ?, ?)",
            params![name, STANDARD.encode(encoded), expires],
        )?;
        Ok(())
    }

    pub fn get(&self, name: &str) -> Result<Option<Value>> {
        let row: Option<(String, i64)> = self
            .db
            .query_row(
                "SELECT value, expires FROM state WHERE key = ?",
                [name],
                |row| Ok((row.get(0)?, row.get(1)?)),
            )
            .optional()?;
        let Some((value, expires)) = row else {
            return Ok(None);
        };
        if expires != 0 && expires <= now()? {
            self.delete(name)?;
            return Ok(None);
        }
        let bytes = STANDARD.decode(value)?;
        if bytes.len() < 28 {
            return Err("invalid encrypted state".into());
        }
        let nonce: [u8; 12] = bytes[..12].try_into()?;
        let mut ciphertext = bytes[28..].to_vec();
        ciphertext.extend_from_slice(&bytes[12..28]);
        let plaintext = self
            .key
            .open_in_place(
                aead::Nonce::assume_unique_for_key(nonce),
                aead::Aad::from(name.as_bytes()),
                &mut ciphertext,
            )
            .map_err(|_| "state authentication failed")?;
        Ok(Some(serde_json::from_slice(plaintext)?))
    }

    pub fn delete(&self, name: &str) -> Result<()> {
        self.db.execute("DELETE FROM state WHERE key = ?", [name])?;
        Ok(())
    }

    pub fn prune(&self) -> Result<()> {
        self.db.execute(
            "DELETE FROM state WHERE expires > 0 AND expires <= ?",
            [now()?],
        )?;
        Ok(())
    }
}

fn now() -> Result<i64> {
    Ok(SystemTime::now()
        .duration_since(UNIX_EPOCH)?
        .as_millis()
        .try_into()?)
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn reads_bun_ciphertext_and_preserves_expiration() -> Result<()> {
        let storage = Storage::open(":memory:", &STANDARD.encode([42; 32]))?;
        // Fixture generated by Bun's createCipheriv with key [42; 32] and IV [7; 12].
        storage.db.execute(
            "INSERT INTO state VALUES ('offset', ?, 0)",
            ["BwcHBwcHBwcHBwcH/ld7rgLbqG7TOYaEr5da4g7NzJFgog=="],
        )?;
        assert_eq!(storage.get("offset")?, Some(json!(123456)));
        storage.set("expired", &json!(1), 1)?;
        assert_eq!(storage.get("expired")?, None);
        storage.set("expired-again", &json!(2), 1)?;
        storage.prune()?;
        assert_eq!(storage.get("expired-again")?, None);
        storage
            .db
            .execute("UPDATE state SET key = 'other' WHERE key = 'offset'", [])?;
        assert!(storage.get("other").is_err());
        Ok(())
    }

    #[test]
    fn bun_and_rust_read_each_others_sqlite_state() -> Result<()> {
        let mut random = [0; 16];
        SystemRandom::new()
            .fill(&mut random)
            .map_err(|_| "random path failed")?;
        let path = std::env::temp_dir().join(format!(
            "wartaq-telegram-{}.sqlite",
            STANDARD.encode(random).replace(['/', '+'], "_")
        ));
        let key = STANDARD.encode([42; 32]);
        let root = Path::new(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .ok_or("missing repository root")?;
        let run = |code: &str| -> Result<()> {
            let status = std::process::Command::new("bun")
                .current_dir(root)
                .arg("-e")
                .arg(code)
                .arg(&path)
                .arg(&key)
                .status()?;
            if !status.success() {
                return Err("Bun compatibility check failed".into());
            }
            Ok(())
        };
        run(
            "import { Storage } from './telegram/storage'; const s = new Storage(process.argv[1], process.argv[2]); s.set('bun', { token: 'synthetic', count: 7 }); s.close()",
        )?;
        {
            let storage = Storage::open(&path, &key)?;
            assert_eq!(
                storage.get("bun")?,
                Some(json!({"token":"synthetic","count":7}))
            );
            storage.set("rust", &json!({"name":"مرحبا","offset":42}), 0)?;
        }
        run(
            "import { Storage } from './telegram/storage'; const s = new Storage(process.argv[1], process.argv[2]); const v = s.get('rust'); s.close(); if (JSON.stringify(v) !== JSON.stringify({name:'مرحبا',offset:42})) process.exit(1)",
        )?;
        std::fs::remove_file(path)?;
        Ok(())
    }
}
